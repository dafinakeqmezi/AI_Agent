"""Evidence validation shared by readiness (Agent 1) and scoring (Agent 2).

Enforces 'never invent evidence': every cited file must exist in the artifact inventory / submission manifest,
and every cited commit must exist in the analysed git history.
"""
from __future__ import annotations

import re

GIT_HISTORY = "(git history)"
COMMIT_RE = re.compile(r"^commit ([0-9a-f]{7,40})$", re.I)
LOC_RE = re.compile(r"^(L\d+(-L?\d+)?|cell \d+.*|p\. ?\d+.*|section .+|-|whole file)$", re.I)


def check_evidence(items, known_paths: set[str] | None, ctx: str, errors: list[str],
                   known_commits: set[str] | None = None) -> None:
    if not isinstance(items, list):
        errors.append(f"{ctx}: evidence must be a list")
        return
    for k, ev in enumerate(items):
        if not isinstance(ev, dict) or not ev.get("file"):
            errors.append(f"{ctx}: evidence[{k}] needs a 'file'")
            continue
        loc = str(ev.get("location", "")).strip()
        if ev["file"] == GIT_HISTORY:
            m = COMMIT_RE.match(loc)
            if not m and loc not in ("-", "whole history"):
                errors.append(f"{ctx}: evidence[{k}] from {GIT_HISTORY} needs location 'commit <sha>' or 'whole history'")
            elif m and known_commits is not None and not any(c.startswith(m.group(1).lower()) for c in known_commits):
                errors.append(f"{ctx}: evidence[{k}] cites commit {m.group(1)}, which is not in the analysed git history")
            elif known_commits is None and m:
                errors.append(f"{ctx}: evidence[{k}] cites a commit but no git history was analysed for this run")
            continue
        f = ev["file"].replace("\\", "/")
        while f.startswith("./"):
            f = f[2:]
        if known_paths is not None and f not in known_paths:
            # allow citing extracted artifacts generated by the toolkit (scan.json, history.md, ...)
            if not f.startswith(("artifacts/", "(")):
                errors.append(f"{ctx}: evidence[{k}] cites '{ev['file']}', which is not in the project/submission "
                              f"(never cite files that do not exist)")
        if not loc:
            errors.append(f"{ctx}: evidence[{k}] ({ev['file']}) needs a 'location' (L<n>, cell <n>, p. <n>, section \"...\")")
        elif not LOC_RE.match(loc):
            errors.append(f"{ctx}: evidence[{k}] location '{loc}' is not in a recognized format")


def commits_from_history(history: dict | None) -> set[str] | None:
    if not history or not history.get("available"):
        return None
    return {c["sha"] for c in history.get("commits", [])}
